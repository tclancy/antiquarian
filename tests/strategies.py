"""Reusable Hypothesis strategies for Antiquarian property tests."""

from __future__ import annotations

from datetime import datetime, timezone

from hypothesis import strategies as st

from antiquarian.models import CommitFeatures, TodoAnnotation


# Known patterns that have caused (or might cause) `claude -p` to hang.
# Mixed into messages alongside arbitrary text to verify the sanitizer
# and prompt builder handle them under fuzzing.
_HANG_PATTERN_FRAGMENTS = [
    "🤖 Generated with [Claude Code](https://claude.ai/code)",
    "Co-Authored-By: Claude <noreply@anthropic.com>",
    "Co-Authored-By: Claude Opus 4.7 (1M context) <noreply@anthropic.com>",
    "Co-Authored-By: Claude Sonnet 4.6 <noreply@anthropic.com>",
    "Generated by AI",
    "🤖",
    "Co-Authored-By: GitHub Copilot <copilot@github.com>",
]


@st.composite
def commit_messages(draw: st.DrawFn) -> str:
    """A commit message — arbitrary text optionally laced with hang-pattern fragments."""
    body = draw(st.text(min_size=0, max_size=2000))
    fragments = draw(
        st.lists(st.sampled_from(_HANG_PATTERN_FRAGMENTS), max_size=4)
    )
    if not fragments:
        return body
    return body + "\n\n" + "\n".join(fragments)


@st.composite
def commit_features(draw: st.DrawFn) -> CommitFeatures:
    """Generate a CommitFeatures with arbitrary but type-valid field values."""
    sha = draw(
        st.text(alphabet="0123456789abcdef", min_size=7, max_size=40)
    )
    return CommitFeatures(
        id=draw(st.text(min_size=1, max_size=30)),
        git_sha=sha,
        jj_change_id=None,
        jj_commit_id=None,
        author=draw(st.text(min_size=1, max_size=80)),
        author_email=draw(st.text(min_size=1, max_size=120)),
        timestamp=draw(
            st.datetimes(
                min_value=datetime(2000, 1, 1),
                max_value=datetime(2030, 1, 1),
                timezones=st.just(timezone.utc),
            )
        ),
        hour_of_day=draw(st.integers(min_value=0, max_value=23)),
        day_of_week=draw(st.integers(min_value=0, max_value=6)),
        message=draw(commit_messages()),
        files_changed=draw(
            st.lists(
                st.text(min_size=1, max_size=120).filter(lambda s: "\x00" not in s),
                max_size=30,
            )
        ),
        additions=draw(st.integers(min_value=0, max_value=1_000_000)),
        deletions=draw(st.integers(min_value=0, max_value=1_000_000)),
        pr_number=draw(st.one_of(st.none(), st.integers(min_value=1, max_value=999_999))),
        pr_body=draw(st.one_of(st.none(), commit_messages())),
    )


@st.composite
def todo_annotations(draw: st.DrawFn) -> TodoAnnotation:
    kind = draw(st.sampled_from(["TODO", "FIXME", "XXX", "HACK"]))
    return TodoAnnotation(
        kind=kind,  # type: ignore[arg-type]
        line_number=draw(st.integers(min_value=1, max_value=100_000)),
        text=draw(st.text(max_size=500)),
        introduced_commit=draw(
            st.text(alphabet="0123456789abcdef", min_size=7, max_size=40)
        ),
        introduced_at=draw(
            st.datetimes(
                min_value=datetime(2000, 1, 1),
                max_value=datetime(2030, 1, 1),
                timezones=st.just(timezone.utc),
            )
        ),
        introduced_by=draw(st.text(min_size=1, max_size=80)),
        age_days=draw(st.integers(min_value=0, max_value=20_000)),
    )
